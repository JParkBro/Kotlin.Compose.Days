internal fun palette(
    type: AppThemeType,
    dark: Boolean,
): AppColors =
    when (type) {
        AppThemeType.PINK -> if (dark) PinkDark else PinkLight
        AppThemeType.NAVY -> if (dark) NavyDark else NavyLight
        AppThemeType.SAGE -> if (dark) SageDark else SageLight
        AppThemeType.LAVENDER -> if (dark) LavenderDark else LavenderLight
    }

